package member;

/*
================================================================
 [복습 3] MemberService.java

 ── 이 파일이 왜 필요한가 ──────────────────────────────────
 Controller 가 DAO 를 직접 불러도 프로그램은 동작한다.
 그런데도 가운데 층을 하나 더 두는 이유가 있다.

   회원가입을 예로 들어 보자.
     "아이디가 이미 있으면 저장하지 않는다"
   이것은 SQL 도 아니고 화면도 아니다. "업무 규칙" 이다.

   이 규칙을 어디에 둘 것인가?
     Controller 에 두면 -> 화면 처리 코드와 업무 규칙이 뒤섞인다
     DAO 에 두면        -> SQL 실행만 해야 할 곳에 판단이 섞인다
   -> 그래서 규칙만 담당하는 층을 따로 만든 것이 Service 다.

 ── 세 계층의 역할 구분 ────────────────────────────────────
   Controller : 요청을 받고, 어느 화면으로 보낼지 정한다
   Service    : 무엇을 어떤 순서로 할지 판단한다   <- 이 파일
   DAO        : SQL 을 실행한다

   Service 는 화면을 모른다  -> request, response 가 등장하지 않는다
   Service 는 SQL 을 모른다  -> select, insert 라는 글자가 없다
   ** 이 두 가지가 이 파일에 없다는 점을 직접 확인해 보자. **

 ── 이 파일의 메소드 10개 ──────────────────────────────────
   단순 전달형 (조건 없이 DAO 결과를 그대로 넘김)
     login, isDuplicated, getMember
   판단형 (조건을 확인하고 흐름을 나눔)
     join, modify, withdraw, findId, findPwd
   도우미
     생성자, isEmpty
================================================================
*/
public class MemberService {

	private MemberDAO memberDAO;
	/* DB 작업을 맡길 DAO 객체를 담아 둘 변수.
	   private 이므로 이 클래스 안에서만 사용된다. */

	/*==============================================================
	  생성자 : DAO 객체를 만들어 변수에 저장한다

	  언제 실행되는가?
	    MemberController 의 init() 에서 new MemberService() 를 할 때.
	    init() 은 서블릿이 처음 만들어질 때 1번만 실행되므로
	    이 생성자도 서버가 켜진 뒤 1번만 실행된다.
	==============================================================*/
	public MemberService() {

		memberDAO = new MemberDAO();
		/* DAO 객체를 만든다.
		   이 순간 MemberDAO 의 생성자가 실행되어
		   커넥션풀(jdbc/jspdb)을 찾아 준비한다.

		   ** 메소드마다 new MemberDAO() 를 하지 않는 이유 **
		   요청이 올 때마다 커넥션풀을 다시 찾는 것은 낭비다.
		   한 번 만들어 두고 계속 재사용한다. */

	}

	/*==============================================================
	  login() : 로그인 업무
	  - 매개변수 : 아이디와 비밀번호가 담긴 상자
	  - 반환값   : true = 로그인 성공 / false = 실패

	  [단순 전달형]
	  판단할 조건이 없어서 DAO 결과를 그대로 넘긴다.
	  "그럼 이 메소드는 왜 있는가?" 하는 의문이 들 수 있다.
	  -> 나중에 "5회 실패하면 계정 잠금", "마지막 접속 시각 기록"
	     같은 규칙이 추가될 자리를 미리 만들어 둔 것이다.
	     Controller 를 고치지 않고 여기만 고치면 된다.
	==============================================================*/
	public boolean login(MemberVO memberVO) {

		boolean result = memberDAO.isExisted(memberVO);
		/* DAO 에게 "이 아이디와 비밀번호의 회원이 있나요?" 라고 묻는다.
		   DAO 가 SQL 을 실행하고 true 또는 false 를 돌려준다. */

		return result;
		/* 받은 결과를 Controller 에게 그대로 전달한다. */

	}//login

	/*==============================================================
	  isDuplicated() : 아이디 중복 검사 업무
	  - 매개변수 : 검사할 아이디
	  - 반환값   : true = 이미 있는 아이디 / false = 사용 가능

	  ** 반환값의 의미를 헷갈리지 말자 **
	    true  = "중복이다" = 가입 불가
	    false = "중복 아니다" = 가입 가능
	  이름이 isDuplicated(중복인가?) 이므로
	  "있으면 true" 가 자연스럽다.
	==============================================================*/
	public boolean isDuplicated(String id) {

		boolean result = memberDAO.isDuplicated(id);
		/* DAO 에게 아이디 존재 여부를 묻는다. */

		return result;

	}//isDuplicated

	/*==============================================================
	  join() : 회원가입 업무
	  - 매개변수 : 네 값이 담긴 상자
	  - 반환값   : true = 가입 성공 / false = 중복이거나 실패

	  [판단형 - 이 파일의 존재 이유를 보여주는 메소드]

	  왜 중복 검사를 먼저 하는가?
	    id 가 기본키(PRIMARY KEY)라서 같은 아이디를 또 넣으면
	    DB 가 오류를 내며 프로그램이 멈춘다.
	    미리 확인해서 오류가 나기 전에 막는 것이다.

	  [실행 순서]
	    1) 중복인지 확인한다
	    2) 중복이면 -> 저장하지 않고 즉시 false 를 돌려준다
	    3) 중복이 아니면 -> 저장하고 그 결과를 돌려준다
	==============================================================*/
	public boolean join(MemberVO memberVO) {

		boolean duplicated = isDuplicated(memberVO.getId());
		/* 상자에서 아이디를 꺼내(getId) 중복 검사를 실행한다.

		   ** memberDAO.isDuplicated 가 아니라
		      이 클래스의 isDuplicated 를 부른 점에 주목하자.
		      이미 만들어 둔 메소드를 재사용한 것이다. ** */

		if (duplicated) {
			return false;
		}
		/* 이미 있는 아이디면 여기서 메소드를 끝낸다.

		   ** return 을 빠뜨리면 어떻게 되는가? **
		   아래 insertMember 까지 실행되어
		   "Duplicate entry" 오류가 발생한다.
		   조건을 검사해 놓고 멈추지 않으면 검사한 의미가 없다.
		   -> 이렇게 조건이 맞을 때 메소드를 즉시 끝내는 방식을
		      "조기 종료" 라고 한다. if-else 로 감싸는 것보다
		      들여쓰기가 얕아져 읽기 편하다. */

		boolean result = memberDAO.insertMember(memberVO);
		/* 여기까지 왔다는 것은 중복이 아니라는 뜻이다.
		   이제 안심하고 저장을 시킨다. */

		return result;

	}//join

	/*==============================================================
	  getMember() : 회원 1명의 정보를 가져오는 업무
	  - 매개변수 : 아이디
	  - 반환값   : 정보가 담긴 상자 / 없으면 null

	  [어디에 쓰이는가]
	  회원정보 수정 화면을 열 때, 입력칸에 기존 정보를
	  미리 채워 넣기 위해 먼저 조회해야 한다.
	  -> MemberController 의 modifyForm() 이 이 메소드를 부른다.
	==============================================================*/
	public MemberVO getMember(String id) {

		MemberVO memberVO = memberDAO.selectMember(id);
		/* DAO 에게 조회를 시키고 상자를 받는다.
		   회원이 없으면 null 이 온다. */

		return memberVO;

	}//getMember

	/*==============================================================
	  modify() : 회원정보 수정 업무
	  - 매개변수 : 수정할 값이 담긴 상자
	  - 반환값   : true = 수정 성공 / false = 실패

	  [판단형]
	  없는 회원을 수정하려 하면 아무 행도 바뀌지 않는데,
	  그래도 오류는 나지 않아서 "성공한 줄" 착각할 수 있다.
	  그래서 존재 여부를 먼저 확인한다.
	==============================================================*/
	public boolean modify(MemberVO memberVO) {

		boolean exists = memberDAO.isDuplicated(memberVO.getId());
		/* isDuplicated 를 "존재 확인" 용도로 재사용했다.

		   ** 이름은 "중복인가?" 지만 하는 일은 "있는가?" 이므로
		      수정에서도 그대로 쓸 수 있다.
		      메소드 하나를 두 곳에서 쓰는 재사용의 예다. ** */

		if (!exists) {
			return false;
		}
		/* 느낌표(!) 는 "반대" 라는 뜻이다.
		     exists 가 true  -> !exists 는 false -> 블록 실행 안 함
		     exists 가 false -> !exists 는 true  -> 블록 실행

		   즉 "회원이 없으면" 여기서 끝낸다는 뜻이다.

		   ** 느낌표를 빼면 정반대로 동작한다.
		      있는 회원만 수정에 실패하는 이상한 결과가 된다. ** */

		boolean result = memberDAO.updateMember(memberVO);
		/* 존재하는 회원이므로 수정을 시킨다. */

		return result;

	}//modify

	/*==============================================================
	  withdraw() : 회원탈퇴 업무
	  - 매개변수 : 아이디와 확인용 비밀번호가 담긴 상자
	  - 반환값   : true = 탈퇴 성공 / false = 비밀번호 불일치 또는 실패

	  [판단형 - 가장 신중해야 하는 메소드]
	  삭제는 되돌릴 수 없다. 그래서 본인 확인을 반드시 거친다.

	  [실행 순서]
	    1) 아이디와 비밀번호가 맞는지 확인한다
	    2) 틀리면 -> 삭제하지 않고 false
	    3) 맞으면 -> 삭제하고 그 결과를 반환
	==============================================================*/
	public boolean withdraw(MemberVO memberVO) {

		boolean isMember = memberDAO.isExisted(memberVO);
		/* isExisted 는 로그인 검증용으로 만든 메소드다.
		   "아이디와 비밀번호가 맞는가?" 를 묻는 일은 똑같으므로
		   탈퇴의 본인 확인에도 그대로 쓴다. (재사용) */

		if (!isMember) {
			return false;
		}
		/* 비밀번호가 틀리면 삭제하지 않고 끝낸다.

		   ** 이 검사가 없으면 어떻게 되는가? **
		   아이디만 알면 누구나 남의 계정을 지울 수 있게 된다.
		   Controller 는 세션에서 아이디를 가져오므로 실제로는
		   본인 계정만 대상이 되지만, Service 단계에서도
		   한 번 더 막는 것이 안전한 설계다. */

		boolean result = memberDAO.deleteMember(memberVO.getId());
		/* 본인이 확인되었으므로 삭제를 시킨다. */

		return result;

	}//withdraw

	/*==============================================================
	  findId() : 아이디 찾기 업무
	  - 매개변수 : 이름, 이메일
	  - 반환값   : 찾은 아이디 / 없으면 null

	  [왜 이름과 이메일 두 개를 요구하는가]
	  이름만으로 찾아 주면
	    - 동명이인이 있을 때 누구의 아이디인지 알 수 없다
	    - 이름만 아는 사람이 남의 아이디를 알아낼 수 있다
	  이메일은 사람마다 다르므로 본인 확인 수단이 된다.
	==============================================================*/
	public String findId(String name, String email) {

		if (isEmpty(name) || isEmpty(email)) {
			return null;
		}
		/* 둘 중 하나라도 비어 있으면 DB 를 다녀오지 않고 끝낸다.

		   || 는 "또는" 이라는 뜻이다.
		     이름이 비었거나 || 이메일이 비었거나 -> 실행

		   ** 왜 미리 걸러내는가? **
		   빈 값으로 조회해 봐야 결과가 없을 것이 뻔한데
		   DB 를 다녀오는 것은 낭비다.
		   사용자가 많은 사이트일수록 이런 차이가 쌓인다. */

		String id = memberDAO.findId(name, email);
		/* 값이 모두 있으므로 조회를 시킨다. */

		return id;

	}//findId

	/*==============================================================
	  findPwd() : 비밀번호 찾기 업무
	  - 매개변수 : 아이디, 이름, 이메일
	  - 반환값   : 찾은 비밀번호 / 없으면 null

	  [왜 확인 항목이 3개인가]
	  비밀번호는 아이디보다 더 중요한 정보이므로
	  본인 확인 조건을 하나 더 늘렸다.
	    아이디 찾기   : 2개 (이름 + 이메일)
	    비밀번호 찾기 : 3개 (아이디 + 이름 + 이메일)

	  [실무와의 차이 - 반드시 알아 둘 것]
	  실제 사이트는 비밀번호를 알려주지 않는다.
	  비밀번호를 알아볼 수 없는 형태로 바꿔 저장하기 때문에
	  꺼내서 보여주는 것 자체가 불가능하다.
	  대신 본인 확인 후 "새 비밀번호를 정하는 화면" 으로 보낸다.
	  이 예제는 비밀번호를 그대로 저장하고 있어 조회가 되는 것이다.
	==============================================================*/
	public String findPwd(String id, String name, String email) {

		if (isEmpty(id) || isEmpty(name) || isEmpty(email)) {
			return null;
		}
		/* 셋 중 하나라도 비어 있으면 조회하지 않는다. */

		String pwd = memberDAO.findPwd(id, name, email);

		return pwd;

	}//findPwd

	/*==============================================================
	  isEmpty() : 값이 비어 있는지 검사하는 도우미 메소드
	  - 매개변수 : 검사할 글자
	  - 반환값   : true = 비어 있음 / false = 값이 있음

	  [왜 메소드로 따로 만들었나]
	  findId 와 findPwd 에서 같은 검사를 5번 해야 한다.
	  같은 코드를 여러 번 쓰면
	    - 고칠 일이 생겼을 때 다섯 곳을 다 고쳐야 하고
	    - 한 곳을 빠뜨리면 버그가 된다
	  하나로 묶으면 여기만 고치면 된다.

	  [private 인 이유]
	  이 클래스 안에서만 쓰는 도우미이므로
	  밖에서 부를 수 없게 private 으로 감췄다.
	==============================================================*/
	private boolean isEmpty(String value) {

		return value == null || value.trim().equals("");
		/* 두 가지 경우를 "비어 있다" 로 판단한다.

		   1) value == null
		      값이 아예 없는 상태.
		      입력칸이 폼에 없거나 이름이 틀렸을 때 발생한다.

		   2) value.trim().equals("")
		      trim() : 앞뒤의 공백을 잘라낸다
		        "  " -> ""       (공백만 입력한 경우)
		        " a " -> "a"
		      equals("") : 잘라낸 결과가 빈 글자인지 확인한다
		      -> 스페이스만 누르고 넘긴 경우도 걸러낸다.

		   ** 순서가 매우 중요하다 **
		   null 검사를 반드시 먼저 해야 한다.
		   순서를 바꾸면 null 인 값에 trim() 을 부르게 되어
		   NullPointerException 오류가 난다.

		   ** || 의 특별한 성질 (단축 평가) **
		   앞 조건이 true 이면 뒤 조건은 아예 확인하지 않는다.
		   그래서 null 일 때 뒤의 trim() 이 실행되지 않아 안전하다.

		   ** 문자열 비교에 == 를 쓰면 안 되는 이유 **
		   value == "" 라고 쓰면 글자가 아니라 "저장 위치"를 비교해
		   내용이 같아도 false 가 나올 수 있다.
		   글자 내용 비교는 반드시 equals 를 쓴다. */

	}//isEmpty

}//MemberService

